"""Tests for the composite/covering indexes on the edge table (Feature 1.1)."""

from io import StringIO

from django.core.management import call_command
from django.test import TestCase

from tests.testapp.models import NetworkEdge


class EdgeCompositeIndexTestCase(TestCase):
    def test_edge_model_declares_both_composite_indexes(self):
        index_field_tuples = {tuple(index.fields) for index in NetworkEdge._meta.indexes}
        self.assertIn(("parent", "child"), index_field_tuples)
        self.assertIn(("child", "parent"), index_field_tuples)

    def test_composite_indexes_have_distinct_autogenerated_names(self):
        # No explicit name= is set in the factory, so Django auto-generates
        # per-concrete-model names. They must be present and unique.
        names = [
            index.name
            for index in NetworkEdge._meta.indexes
            if tuple(index.fields) in {("parent", "child"), ("child", "parent")}
        ]
        self.assertEqual(len(names), 2)
        self.assertTrue(all(names))
        self.assertEqual(len(set(names)), 2)


class NoMissingMigrationsTestCase(TestCase):
    def test_makemigrations_reports_no_changes(self):
        """makemigrations --check exits 1 when a model change lacks a migration.

        It exits 2 for a bad app label (a test-environment problem, not a
        missing migration), so distinguish the two by the exit code.
        """
        out = StringIO()
        try:
            call_command(
                "makemigrations",
                "testapp",
                check=True,
                dry_run=True,
                verbosity=0,
                stdout=out,
                stderr=out,
            )
        except SystemExit as exc:
            if exc.code == 1:
                self.fail(f"Missing migration detected by makemigrations --check: {out.getvalue()}")
            # exc.code == 2 (or other) => environment/app-label problem, re-raise
            raise
